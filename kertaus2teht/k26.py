def summa(a, b):
    return a + b

def erotus(a, b):
    return a - b

def tulo(a, b):
    return a * b

def jako(a, b):
    return a / b

a = int(input("Anna ensimmäinen luku: "))
b = int(input("Anna toinen luku: "))

print("Summa:", summa(a, b))
print("Erotus:", erotus(a, b))
print("Tulo:", tulo(a, b))
print("Jako:", jako(a, b))